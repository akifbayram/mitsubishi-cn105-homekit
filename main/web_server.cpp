// Disable Nagle on every new connection — eliminates up-to-200ms delay on small
// writes (WebSocket state pushes, log lines).  Called by esp_http_server via open_fn.
static esp_err_t setTcpNoDelay(httpd_handle_t, int sockfd) {
    int flag = 1;
    setsockopt(sockfd, IPPROTO_TCP, TCP_NODELAY, &flag, sizeof(flag));
    LOG_DEBUG("HTTP: new connection accepted (fd=%d)", sockfd);
    return ESP_OK;
}

// ── Embedded binary assets (generated by CMake target_add_binary_data) ──────
extern const uint8_t web_ui_html_gz_start[] asm("_binary_web_ui_html_gz_start");
extern const uint8_t web_ui_html_gz_end[]   asm("_binary_web_ui_html_gz_end");
extern const uint8_t recovery_html_gz_start[] asm("_binary_recovery_html_gz_start");
extern const uint8_t recovery_html_gz_end[]   asm("_binary_recovery_html_gz_end");
extern const uint8_t icon_192_png_start[] asm("_binary_icon_192_png_start");
extern const uint8_t icon_192_png_end[]   asm("_binary_icon_192_png_end");
extern const uint8_t icon_512_png_start[] asm("_binary_icon_512_png_start");
extern const uint8_t icon_512_png_end[]   asm("_binary_icon_512_png_end");
extern const uint8_t favicon_png_start[]  asm("_binary_favicon_png_start");
extern const uint8_t favicon_png_end[]    asm("_binary_favicon_png_end");

// ── Content-derived ETag — CRC32 of the embedded assets, so it changes exactly
//    when they do. (A __DATE__/__TIME__ stamp goes stale: an OTA that only
//    changes the HTML doesn't recompile this file, so browsers would keep the
//    old page via 304.) Computed once on first use; magic-static is thread-safe.
static const char* assetEtag() {
    static const auto etag = [] {
        uint32_t crc = 0;
        crc = esp_rom_crc32_le(crc, web_ui_html_gz_start,   (uint32_t)(web_ui_html_gz_end   - web_ui_html_gz_start));
        crc = esp_rom_crc32_le(crc, recovery_html_gz_start, (uint32_t)(recovery_html_gz_end - recovery_html_gz_start));
        crc = esp_rom_crc32_le(crc, icon_192_png_start,     (uint32_t)(icon_192_png_end     - icon_192_png_start));
        crc = esp_rom_crc32_le(crc, icon_512_png_start,     (uint32_t)(icon_512_png_end     - icon_512_png_start));
        crc = esp_rom_crc32_le(crc, favicon_png_start,      (uint32_t)(favicon_png_end      - favicon_png_start));
        std::array<char, 12> e{};
        snprintf(e.data(), e.size(), "\"%08lx\"", (unsigned long)crc);
        return e;
    }();
    return etag.data();
}

// Return true (and send 304) if the client already has the current version
static bool sendNotModified(httpd_req_t *req) {
    char buf[64];
    if (httpd_req_get_hdr_value_str(req, "If-None-Match", buf, sizeof(buf)) == ESP_OK &&
        strcmp(buf, assetEtag()) == 0) {
        httpd_resp_set_status(req, "304 Not Modified");
        httpd_resp_send(req, NULL, 0);
        return true;
    }
    return false;
}

