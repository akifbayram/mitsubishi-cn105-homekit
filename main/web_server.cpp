// ══════════════════════════════════════════════════════════════════════════════
// HTTP handler: GET /  (serve embedded gzipped HTML)
// ══════════════════════════════════════════════════════════════════════════════

esp_err_t WebUI::sendGzipPage(httpd_req_t *req, const uint8_t *data, size_t len) {
    if (sendNotModified(req)) return ESP_OK;
    httpd_resp_set_type(req, "text/html");
    httpd_resp_set_hdr(req, "Content-Encoding", "gzip");
    httpd_resp_set_hdr(req, "Cache-Control", "no-cache");
    httpd_resp_set_hdr(req, "ETag", assetEtag());
    httpd_resp_send(req, (const char *)data, len);
    return ESP_OK;
}

// True if the request's peer is on the fallback AP subnet (192.168.4.0/24).
static bool isApSubnetClient(httpd_req_t *req) {
    int fd = httpd_req_to_sockfd(req);
    struct sockaddr_storage saddr;
    socklen_t addrLen = sizeof(saddr);
    if (getpeername(fd, (struct sockaddr *)&saddr, &addrLen) != 0) return false;
    uint32_t ip = 0;
    if (saddr.ss_family == AF_INET) {
        ip = ntohl(((struct sockaddr_in *)&saddr)->sin_addr.s_addr);
    } else if (saddr.ss_family == AF_INET6) {
        // IPv4-mapped IPv6: ::ffff:x.x.x.x — last 4 bytes are the IPv4 address
        struct sockaddr_in6 *a6 = (struct sockaddr_in6 *)&saddr;
        uint8_t *b = a6->sin6_addr.s6_addr;
        if (b[10] == 0xFF && b[11] == 0xFF) {
            ip = ((uint32_t)b[12] << 24) | ((uint32_t)b[13] << 16) |
                 ((uint32_t)b[14] << 8)  |  (uint32_t)b[15];
        }
    }
    // AP subnet: 192.168.4.0/24 = 0xC0A80400
    return ip && (ip & 0xFFFFFF00) == 0xC0A80400;
}

esp_err_t WebUI::handleRoot(httpd_req_t *req) {
    // If AP fallback is active and the client is on the AP subnet, serve the
    // WiFi setup page instead of the main UI.
    if (webUI._apMode && isApSubnetClient(req)) {
        return handleRecoveryPage(req);
    }

    return sendGzipPage(req, web_ui_html_gz_start,
                        (size_t)(web_ui_html_gz_end - web_ui_html_gz_start));
}

esp_err_t WebUI::handleRecoveryPage(httpd_req_t *req) {
    return sendGzipPage(req, recovery_html_gz_start,
                        (size_t)(recovery_html_gz_end - recovery_html_gz_start));
}

// ── CNA (Captive Network Assistant) detection page ──────────────────────────
// Served on port 80 to trigger captive portal popups on iOS/macOS/Android/Windows.
// Returns 200 with HTML (not 302) so all platforms detect the captive portal.
static const char CNA_PAGE[] =
    "<!DOCTYPE html><html><head>"
    "<meta http-equiv=\"refresh\" content=\"0;url=http://192.168.4.1/\">"
    "<meta name=\"viewport\" content=\"width=device-width,initial-scale=1\">"
    "<title>WiFi Setup</title>"
    "<style>body{font-family:-apple-system,system-ui,sans-serif;background:#000;"
    "color:#fff;display:flex;justify-content:center;align-items:center;"
    "min-height:100vh;margin:0;text-align:center}"
    "a{color:#007AFF;font-size:17px;text-decoration:none}</style>"
    "</head><body><div>"
    "<p style=\"font-size:15px;color:#8E8E93;margin-bottom:16px\">"
    "Redirecting to WiFi setup&hellip;</p>"
    "<a href=\"http://192.168.4.1/\">Tap here if not redirected</a>"
    "</div></body></html>";

static void serveCNAPage(httpd_req_t *req) {
    httpd_resp_set_type(req, "text/html");
    httpd_resp_set_hdr(req, "Cache-Control", "no-store");
    httpd_resp_sendstr(req, CNA_PAGE);
}

// Catch-all 404 handler installed only while the fallback AP is active. Serves
// the captive-portal page to AP-subnet clients (triggers the OS popup); any
// other client gets a normal 404 so the main UI behaves normally.
static esp_err_t handleRedirect404(httpd_req_t *req, httpd_err_code_t) {
    if (webUI.isAPMode() && isApSubnetClient(req)) {
        serveCNAPage(req);
        return ESP_OK;
    }
    httpd_resp_send_err(req, HTTPD_404_NOT_FOUND, "Not found");
    return ESP_FAIL;
}

// ══════════════════════════════════════════════════════════════════════════════
// WiFi status and setup handlers
// ══════════════════════════════════════════════════════════════════════════════

esp_err_t WebUI::handleWifiStatus(httpd_req_t *req) {
    // Load cached SSID from NVS
    char ssid[33] = "";
    char pass[65] = "";
    WifiManager::loadCredentials(ssid, sizeof(ssid), pass, sizeof(pass));

    const DeviceSettings &cfg = settings.get();
    bool connected = WifiManager::isConnected();

    char escSSID[67], escName[65];
    jsonEscape(ssid, escSSID, sizeof(escSSID));
    jsonEscape(cfg.deviceName, escName, sizeof(escName));

    // "joined" = connected on the credentials last applied. The bare
    // connected level stays true for the OLD network throughout a
    // dial-initiated change window — the page's join poll must not key
    // success off it (on-device round 2, 2026-07-12).
    bool joined = connected && !WifiManager::isJoinPending();

    char buf[300];
    snprintf(buf, sizeof(buf),
        "{\"ssid\":\"%s\",\"deviceName\":\"%s\",\"connected\":%s"
        ",\"joined\":%s,\"hkSetupCode\":\"%s\"}",
        escSSID, escName, connected ? "true" : "false",
        joined ? "true" : "false",
        homekit_get_setup_code());

    httpd_resp_set_type(req, "application/json");
    httpd_resp_sendstr(req, buf);
    return ESP_OK;
}

esp_err_t WebUI::handleWifiScan(httpd_req_t *req) {
    WifiManager::ScannedNetwork networks[15];
    int count = WifiManager::scanNetworks(networks, 15);

    char buf[1200];
    int pos = 0;
    jsonAppend(buf, sizeof(buf), &pos, "[");
    for (int i = 0; i < count; i++) {
        char escSSID[67];
        jsonEscape(networks[i].ssid, escSSID, sizeof(escSSID));
        jsonAppend(buf, sizeof(buf), &pos,
            "%s{\"ssid\":\"%s\",\"rssi\":%d,\"secure\":%s}",
            i > 0 ? "," : "",
            escSSID,
            (int)networks[i].rssi,
            networks[i].secure ? "true" : "false");
        if (pos >= (int)sizeof(buf) - 80) break;
    }
    jsonAppend(buf, sizeof(buf), &pos, "]");

    httpd_resp_set_type(req, "application/json");
    httpd_resp_set_hdr(req, "Cache-Control", "no-store");
    httpd_resp_sendstr(req, buf);
    return ESP_OK;
}

bool WebUI::applyWifiCredentials(const char *json, const char **outError) {
    char ssid[33] = {0};
    char password[65] = {0};
    if (!jsonGetString(json, "ssid", ssid, sizeof(ssid)) || strlen(ssid) == 0) {
        *outError = "SSID is required";
        return false;
    }
    // Password is optional (open networks send empty password)
    jsonGetString(json, "password", password, sizeof(password));
    LOG_INFO("Saving WiFi credentials (SSID: %s)", ssid);
    eventlog_append(EV_WIFI_CREDS_CHANGED);
    // Connect via WifiManager (saves to NVS and initiates connection)
    WifiManager::connect(ssid, password);
    // Mark change pending (shorter recovery timeout); also refreshes the
    // cached SSID from the just-saved credentials
    wifiRecovery.setChangePending(true);
    // Let the change window close on join success (and stop treating STA
    // reconnects as old-network blips)
    wifiRecovery.noteReprovision();
    return true;
}

esp_err_t WebUI::handleWifiSetup(httpd_req_t *req) {
    char body[150] = {0};
    int received = httpd_req_recv(req, body, sizeof(body) - 1);
    if (received <= 0) {
        httpd_resp_send_err(req, HTTPD_400_BAD_REQUEST, "Empty request");
        return ESP_FAIL;
    }
    body[received] = '\0';

    const char *error = nullptr;
    if (!webUI.applyWifiCredentials(body, &error)) {
        httpd_resp_send_err(req, HTTPD_400_BAD_REQUEST, error);
        return ESP_FAIL;
    }

    httpd_resp_set_type(req, "application/json");
    httpd_resp_sendstr(req, "{\"status\":\"saved\"}");
    return ESP_OK;
}

// ══════════════════════════════════════════════════════════════════════════════
// AP mode (captive portal handler on the port-80 web server)
// ══════════════════════════════════════════════════════════════════════════════

// The web UI now owns port 80, so the captive portal no longer needs a separate
// server: while the fallback AP is active we install a catch-all 404 handler on
// the main server that serves the captive-portal page to AP-subnet clients.
// handleRoot already routes AP-subnet clients to the WiFi setup page.
void WebUI::setAPMode(bool active) {
    if (active == _apMode) return;
    _apMode = active;
    applyCaptivePortalHandler();
}

void WebUI::applyCaptivePortalHandler() {
    if (!_server) return;  // begin() re-applies this once the server is up
    if (_apMode) {
        // Catch OS captive portal probes (/generate_204, /connecttest.txt, etc.)
        httpd_register_err_handler(_server, HTTPD_404_NOT_FOUND, handleRedirect404);
        LOG_INFO("Captive portal handler enabled (AP mode)");
    } else {
        httpd_register_err_handler(_server, HTTPD_404_NOT_FOUND, NULL);
        LOG_INFO("Captive portal handler disabled");
    }
}

